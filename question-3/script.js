//Unary Operators
let a = 5;
let b = 2;
console.log("a = ", a, "& b = ",b);
a++;
console.log("a = ",a);//6
b++;
console.log("b = ",b);//3
// a++ and b++ are post-increment operators, which means that the value of a and b will be incremented after the current expression is evaluated. So, when we log the value of a and b after the increment, we see the updated values.
a--;
console.log("a = ",a);//5
b--;
console.log("b = ",b);//2
// take new values
let x= 5;
let y= 2;
console.log("x = ", x, "& y = ",y);
x--;
console.log("x = ",x);//4
y--;
console.log("y = ",y);//1